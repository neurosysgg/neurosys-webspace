    private static function siteHeader(): string
    {
        $profile = new SoundCloudProfileEmbed();
        $options = $profile->options->map(static fn(BackedEnum $option): string => (string) $option->value)->join(' ');
        $lines   = [
            self::HEADER,
            '#ifndef NS_SITE_H',
            '#define NS_SITE_H',
            '',
            '/* Site\'s identity and the asset manifest of the build it was printed from */',
            '#define NS_NAME ' . self::c(Site::NAME),
            '#define NS_EMAIL ' . self::c(Site::EMAIL),
            '#define NS_DEMO_USER ' . self::c(Site::DEMO_USER),
            '#define NS_FILE_HOST ' . self::c(Site::FILE_HOST),
            '#define NS_PLAYER_HOST ' . self::c(Site::PLAYER_HOST),
            '#define NS_COVER_PLACEHOLDER ' . self::c(Site::COVER_PLACEHOLDER),
            '#define NS_STYLESHEET ' . self::c(AssetManifest::STYLESHEET),
            '#define NS_CHARSET ' . self::c(Charset::Utf8->canonical()),
            '#define NS_VIEWPORT '
                . self::c(new ViewportContent(width: ViewportWidth::Device, initialScale: 1.0)->render()),
            '#define NS_ADMIN_PATH ' . self::c(AdminPath::Index->to()),
            '#define NS_ENDONYM_EN ' . self::c(Language::English->endonym()),
            '#define NS_ENDONYM_DE ' . self::c(Language::German->endonym()),
            '#define NS_SCRIPT ' . self::c(AssetManifest::SCRIPT),
            '',
            '/* the profile embed on the home page (SoundCloudProfileEmbed\'s defaults) */',
            '#define NS_PROFILE_STYLE ' . self::c($profile->style->value),
            '#define NS_PROFILE_OPTIONS ' . self::c($options),
            '#define NS_PROFILE_HEIGHT ' . self::c((string) $profile->height()),
            '',
            '/* the modules the page preloads, in the manifest\'s order */',
            'extern const char *const ns_modules[];',
            'extern const int ns_nmodules;',
            '',
            '#endif',
        ];

        return implode("\n", $lines) . "\n";
    }

    /** @return string */
    private static function site(): string
    {
        $lines = [self::HEADER, '#include "site.h"', '', 'const char *const ns_modules[] = {'];
        foreach (AssetManifest::MODULES as $module) {
            $lines[] = '    ' . self::c($module) . ',';
        }
        $lines[] = '    "",';
        $lines[] = '};';
        $lines[] = 'const int ns_nmodules = ' . count(AssetManifest::MODULES) . ';';

        return implode("\n", $lines) . "\n";
    }

    // ───────────────────────────── releases and profiles ─────────────────────────────

    /** @return string */
    private static function releases(): string
    {
        $lines = [self::HEADER, '#include "model.h"', '#include "texts.h"', ''];
        $rows  = [];
        $i     = 0;
        foreach (new ReleaseRepository()->all() as $slug => $release) {
            $rows[] = self::release($lines, $i++, (string) $slug, $release);
        }
        $lines[] = 'const NS_RELEASE ns_releases[] = {';
        foreach ($rows as $row) {
            $lines[] = $row;
        }
        $lines[] = '    {0},';
        $lines[] = '};';
        $lines[] = 'const int ns_nreleases = ' . count($rows) . ';';
        $lines[] = '';
        $lines[] = 'const NS_PROFILE ns_profiles[] = {';
        $count   = 0;
        foreach (new ProfileRepository()->all() as $profile) {
            $lines[] = self::profile($profile);
            $count++;
        }
        $lines[] = '    {0},';
        $lines[] = '};';
        $lines[] = "const int ns_nprofiles = $count;";

        return implode("\n", $lines) . "\n";
    }

    /**
     * The tables release $i needs printed into $lines, and its row of ns_releases[].
     *
     * @param list<string> $lines
     * @param int          $i
     * @param string       $slug
     * @param Release      $release
     * @return string
     */
    private static function release(array &$lines, int $i, string $slug, Release $release): string
    {
        $bpm         = $release->bpm;
        $arrangement = $release->arrangement;
        $sections    = $arrangement === null ? [] : $arrangement->sections->toValues();
        $lines[]     = "static const NS_SECTION sections_{$i}[] = {";
        foreach ($sections as $section) {
            /** @var Section $section */
            $lines[] = sprintf(
                '    {%s, %s, %s},',
                $section->kind === null ? 'NULL' : self::c($section->kind->value),
                self::c($section->timestamp($bpm, $arrangement->ppq)),
                self::c($section->label),
            );
        }
        $lines[] = '    {0},';
        $lines[] = '};';
        $lines[] = "static const NS_FORMAT formats_{$i}[] = {";
        foreach ($release->formats as $format) {
            /** @var Format $format */
            $lines[] = sprintf(
                '    {%s, %s, %s, %s},',
                self::c($format->type->value),
                self::c($format->type->label()),
                self::meta($format->type),
                $format->link === null ? 'NULL' : self::c($format->link->url()),
            );
        }
        $lines[] = '    {0},';
        $lines[] = '};';
        $embed = $release->embed;
        if ($embed instanceof SoundCloudEmbed) {
            $options = $embed->options
                ->map(static fn(BackedEnum $option): string => (string) $option->value)
                ->join(' ');
            $lines[] = sprintf(
                'static const NS_EMBED embed_%d = {%s, %s, %s, %s, %s, %s};',
                $i,
                self::c((string) $embed->trackId),
                self::c($embed->permalink),
                $embed->secretToken ? self::c($embed->secretToken) : 'NULL',
                self::c($embed->style->value),
                self::c($options),
                self::c((string) $embed->height()),
            );
        }
        // A description reads the same in every language, or has a text per language — the one
        // the file leaves out already fallen back, as the PHP renders it.
        $description = $release->description;
        $lines[]     = $description instanceof Verbatim
            ? sprintf(
                'static const CSERVE_TR description_%d = {.kind = CSERVE_TR_VERBATIM, .s = %s};',
                $i,
                self::c($description->text),
            )
            : sprintf(
                'static const CSERVE_TR description_%d = CSERVE_TEXT_IN(%s);',
                $i,
                Site::current()->languages()->offered()
                    ->map(static fn(Language $language): string => self::c($description->in($language)))
                    ->join(', '),
            );
        $lines[] = '';
        $time      = $release->timeSpent;
        $plugins   = $release->madeWith->map(static fn(Plugin $plugin): string => $plugin->name)->join(', ');

        return sprintf(
            '    {%s, %s, %d, &%s, %s, %s, %s, %s, %s, %s, sections_%d, %d, formats_%d, %d},',
            self::c($slug),
            self::c($release->title),
            $bpm,
            self::textId($release->key),
            self::c($release->genre->value),
            "&description_$i",
            self::c($release->cover?->url() ?? Site::COVER_PLACEHOLDER),
            $time === null ? 'NULL' : self::c($time->render()),
            $release->madeWith->isEmpty() ? 'NULL' : self::c($plugins),
            $embed instanceof SoundCloudEmbed ? "&embed_$i" : 'NULL',
            $i,
            count($sections),
            $i,
            $release->formats->count(),
        );
    }

    /**
     * What a download card says under a format's name (ReleaseView::formatMeta()).
     *
     * @param ReleaseFormat $format
     * @return string
     */
    private static function meta(ReleaseFormat $format): string
    {
        return match ($format) {
            ReleaseFormat::STEMS => 'NS_META_STEMS',
            ReleaseFormat::MP3   => 'NS_META_MP3',
            ReleaseFormat::OGG   => 'NS_META_OGG',
            default              => $format->isLossless() ? 'NS_META_LOSSLESS' : 'NS_META_LOSSY',
        };
    }

    /**
     * @param Profile $profile
     * @return string
     */
    private static function profile(Profile $profile): string
    {
        $platform = $profile->platform;

        return sprintf(
            '    {%s, &%s, %s, %s},',
            self::c($profile->url),
            self::textId($platform->label()),
            self::c($platform->iconSrc()),
            self::c((string) $platform->iconHeight()),
        );
    }

    // ───────────────────────────── the privacy policy ─────────────────────────────

    /** @return string */
    private static function privacy(): string
    {
        $lines = [
            self::HEADER,
            '/* data/privacy.{en,de}.html, parsed against the site\'s vocabulary when this was',
            ' * printed: a tree built here, so the app parses no HTML */',
            '#include "html.h"',
            '#include "views.h"',
            '',
        ];
        foreach (['en' => DataFile::PrivacyEnglish, 'de' => DataFile::PrivacyGerman] as $lang => $file) {
            $nodes   = MarkupParser::parse(Site::current()->dataFile($file)->read() ?? '')->toValues();
            $lines[] = "const CSERVE_NODE *ns_privacy_$lang(CSERVE_ARENA *a) {";
            $lines[] = '  return cserve_fragment(a,';
            $parts   = [];
            foreach ($nodes as $node) {
                $parts[] = self::node($node, 2);
            }
            $lines[] = implode(",\n", $parts) . ');';
            $lines[] = '}';
            $lines[] = '';
        }

        return implode("\n", $lines);
    }

    /**
     * $node as the C that builds it, indented $depth.
     *
     * @param Node $node
     * @param int  $depth
     * @return string
     */
    private static function node(Node $node, int $depth): string
    {
        $pad = str_repeat('  ', $depth);
        if ($node instanceof Text) {
            return $pad . 'cserve_text(a, ' . self::c($node->text) . ')';
        }
        if (!$node instanceof Element) {
            throw new TranslationException('the privacy policy parsed into a ' . $node::class);
        }
        $tag        = new ReflectionProperty(Element::class, 'tag')->getValue($node);
        $attributes = new ReflectionProperty(Element::class, 'attributes')->getValue($node);
        $children   = new ReflectionProperty(Element::class, 'children')->getValue($node);
        $built      = 'cserve_el(a, &cserve_tag_' . self::ident($tag->tagName()) . ')';
        foreach ($attributes as $attribute) {
            $built = sprintf(
                'cserve_attr(a, %s, &cserve_attr_%s, %s)',
                $built,
                self::ident($attribute->name->attribute()),
                self::c((string) $attribute->value),
            );
        }
        $kids = [];
        foreach ($children as $child) {
            $kids[] = self::node($child, $depth + 1);
        }

        return $kids === []
            ? $pad . $built
            : $pad . 'cserve_containing(a, ' . $built . ",\n" . implode(",\n", $kids) . ')';
    }

    // ───────────────────────────── C ─────────────────────────────

    /**
     * $s as a C string literal: printable ASCII as itself, anything else — a quote, a backslash, a
     * '<' (the lint's markup check), a '?' (a trigraph) — as a three-digit octal escape.
     *
     * @param string $s
     * @return string
     */
    private static function c(string $s): string
    {
        $out = '"';
        foreach (str_split($s) as $ch) {
            $out .= preg_match('/[A-Za-z0-9 _.,:;=+\-\/*#&>()\[\]{}!%@^~|$`\']/', $ch) === 1
                ? $ch
                : sprintf('\\%03o', ord($ch));
        }

        return $out . '"';
    }

    /**
     * A name as part of a C identifier: "track-id" is track_id.
     *
     * @param string $name
     * @return string
     */
    private static function ident(string $name): string
    {
        return str_replace('-', '_', $name);
    }

    /**
     * A case's name in capitals: "NotYetAvailable" is NOT_YET_AVAILABLE, "CSharpMajor" C_SHARP_MAJOR.
     *
     * @param string $name
     * @return string
     */
    private static function snake(string $name): string
    {
        return strtoupper(preg_replace('/(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])/', '_', $name));
    }
