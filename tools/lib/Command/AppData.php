/**
 * What the site's C app (`app/`, served by c-serve) is compiled with, printed from the PHP that
 * states it today: every catalog case in both languages, the site's own elements, attributes and
 * classes, the asset manifest, the releases (out of `data/releases.json`, every derived value worked
 * out) and profiles, and the privacy policy as a tree (docs/research/c-serve.md, phase c4). The
 * demos are not here: the app reads `data/demos.json` itself, at start-up.
 *
 *   php tools/app-data.php            # write app/gen/
 *   php tools/app-data.php --check    # write nothing; fail on a file that has drifted
 *   php tools/app-data.php --prod     # build/dist/app/: the app's sources, its gen/ on the prod manifest
 *
 * `--prod` is the production tree's half (docs/research/comms.md, m2): `cserve-static` built from
 * `build/dist/app/` serves `build/dist/public/`, whose stylesheet and bundle have their own stamp and
 * no preloads. The prod manifest is the same class as the debug one, so it is loaded before anything
 * could load `src/`'s — and refused if something already did. Like the rest of `build/dist/`, the
 * tree is derived and never committed; the committed `app/gen/` stays the debug one `diff.sh` holds
 * to PHP.
 *
 * The PHP and the data files are the one source of all of it: a word, a release or a class name is
 * changed there and printed here, never edited in `app/gen/`. The output is deterministic,
 * so an unchanged site prints unchanged files, and `npm run build` runs this last.
 */
final readonly class AppData implements Command
{
    /** The catalogs the app's pages say anything from, and the prefix each one's cases take. */
    private const array CATALOGS = [
        'LAYOUT'      => LayoutText::class,
        'HOME'        => HomeText::class,
        'RELEASE'     => ReleaseText::class,
        'KEY'         => MusicalKey::class,
        'DEMO'        => DemoText::class,
        'ERROR'       => ErrorText::class,
        'TERMINAL'    => TerminalText::class,
        'PROFILE'     => ProfileText::class,
    ];

    /** The site's own attribute enums, and the prefix each one's identifiers take. */
    private const array ATTRIBUTES = [
        'card'          => CardAttribute::class,
        'cover_art'     => CoverArtAttribute::class,
        'waveform'      => WaveformAttribute::class,
        'arrangement'   => ArrangementAttribute::class,
        'terminal'      => TerminalAttribute::class,
        'embed'         => EmbedAttribute::class,
        'player'        => SoundCloudPlayerAttribute::class,
    ];

    private const string HEADER = '/* GENERATED by neurosys tools/app-data.php from the PHP site — never edit. */';

    /** @return string */
    public function name(): string
    {
        return 'app-data';
    }

    /** @return string */
    public function usage(): string
    {
        return '[--check | --prod]';
    }

    /** @return string */
    public function description(): string
    {
        return "Print the C app's data (app/gen/) from the PHP site.";
    }

    /** @return list<AppDataOption> */
    public function options(): array
    {
        return AppDataOption::cases();
    }

    /** @return Arity */
    public function operands(): Arity
    {
        return Arity::none();
    }

    /**
     * @param Input  $input
     * @param Output $output
     * @return ExitCode
     */
    public function run(Input $input, Output $output): ExitCode
    {
        $root = dirname(__DIR__, 3);
        $prod = $input->has(AppDataOption::Prod);
        if ($prod && $input->has(AppDataOption::Check)) {
            $output->error("app-data: --check and --prod are two different runs\n");

            return ExitCode::Usage;
        }
        if ($prod && !self::loadProdManifest($root, $output)) {
            return ExitCode::Failure;
        }
        $gen   = $prod ? 'build/dist/app/gen' : 'app/gen';
        $files = [
            "$gen/texts.h"    => self::textsHeader(),
            "$gen/texts.c"    => self::texts(),
            "$gen/vocab.h"    => self::vocabHeader(),
            "$gen/vocab.c"    => self::vocab(),
            "$gen/site.h"     => self::siteHeader(),
            "$gen/site.c"     => self::site(),
            "$gen/releases.c" => self::releases(),
            "$gen/privacy.c"  => self::privacy(),
        ];

        if ($input->has(AppDataOption::Check)) {
            $drifted = 0;
            foreach ($files as $path => $text) {
                if (!is_file("$root/$path") || file_get_contents("$root/$path") !== $text) {
                    $output->error("  $path: not what tools/app-data.php writes — run it\n");
                    $drifted++;
                }
            }

            return $drifted === 0 ? ExitCode::Success : ExitCode::Failure;
        }

        if ($prod) {
            self::copySources("$root/app", "$root/build/dist/app");
            $output->error("  copied app/'s sources to build/dist/app/\n");
        }
        if (!is_dir("$root/$gen")) {
            mkdir("$root/$gen", 0775, true);
        }
        foreach ($files as $path => $text) {
            file_put_contents("$root/$path", $text);
            $output->error("  wrote $path\n");
        }

        return ExitCode::Success;
    }

    /**
     * `build/dist/`'s manifest loaded as {@link AssetManifest}, before anything loads `src/`'s.
     *
     * @param string $root
     * @param Output $output
     * @return bool false, with why on stderr, when there is no prod build or the debug class won
     */
    private static function loadProdManifest(string $root, Output $output): bool
    {
        $manifest = "$root/build/dist/src/NeuroSYS/AssetManifest.php";
        if (!is_file($manifest)) {
            $output->error("app-data: no $manifest — run npm run build:prod\n");

            return false;
        }
        if (class_exists(AssetManifest::class, false)) {
            $output->error("app-data: src/'s AssetManifest was loaded before the prod one could be\n");

            return false;
        }
        require $manifest;

        return true;
    }

    /**
     * Every `.c` and `.h` of the app's own (not `gen/`, which is printed) copied into `$to`, at the
     * same relative path.
     *
     * @param string $from
     * @param string $to
     * @return void
     */
    private static function copySources(string $from, string $to): void
    {
        $files = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($from, \FilesystemIterator::SKIP_DOTS),
        );
        foreach ($files as $file) {
            $relative = substr($file->getPathname(), strlen($from) + 1);
            if (str_starts_with($relative, 'gen/') || !preg_match('/\.[ch]\z/', $relative)) {
                continue;
            }
            $dir = dirname("$to/$relative");
            if (!is_dir($dir)) {
                mkdir($dir, 0775, true);
            }
            copy($file->getPathname(), "$to/$relative");
        }
    }

    // ───────────────────────────── the catalogs ─────────────────────────────

    /** @return list<array{string, Translatable}> every case the app may say, with its identifier */
    private static function catalog(): array
    {
        $cases = [];
        foreach (self::CATALOGS as $prefix => $enum) {
            foreach ($enum::cases() as $case) {
                $cases[] = ['T_' . $prefix . '_' . self::snake($case->name), $case];
            }
        }
        $cases[] = ['T_FRAMEWORK_READ_ONLY', FrameworkText::ReadOnly];

        return $cases;
    }

    /**
     * A catalog case's identifier, from the case that names it.
     *
     * @param Translatable $case
     * @return string
     */
    private static function textId(Translatable $case): string
    {
        foreach (self::catalog() as [$id, $known]) {
            if ($known === $case) {
                return $id;
            }
        }
        throw new TranslationException(sprintf('%s is in no catalog app-data prints', $case::class));
    }

    /** @return string */
    private static function textsHeader(): string
    {
        $lines = [self::HEADER, '#ifndef NS_TEXTS_H', '#define NS_TEXTS_H', '', '#include "text.h"', ''];
        foreach (self::catalog() as [$id]) {
            $lines[] = "extern const CSERVE_TEXT $id;";
        }
        $lines[] = '';
        $lines[] = '/* every one of them, for init()\'s check */';
        $lines[] = 'extern const CSERVE_TEXT *const ns_texts[];';
        $lines[] = 'extern const int ns_ntexts;';
        $lines[] = '';
        $lines[] = '#endif';

        return implode("\n", $lines) . "\n";
    }

    /** @return string */
    private static function texts(): string
    {
        $lines = [
            self::HEADER,
            '#include "texts.h"',
            '',
            '/* English, then German: the app\'s languages in its order, each one an argument */',
            '#define T(id, en, de) const CSERVE_TEXT id = CSERVE_TEXT_IN(en, de)',
        ];
        $ids = [];
        foreach (self::catalog() as [$id, $case]) {
            $translation = $case->translation();
            $lines[]     = sprintf(
                'T(%s, %s, %s);',
                $id,
                self::c($translation->pattern(Language::English)),
                self::c($translation->pattern(Language::German)),
            );
            $ids[] = "&$id";
        }
        $lines[] = '#undef T';
        $lines[] = '';
        $lines[] = 'const CSERVE_TEXT *const ns_texts[] = {';
        foreach ($ids as $id) {
            $lines[] = "    $id,";
        }
        $lines[] = '};';
        $lines[] = 'const int ns_ntexts = (int)(sizeof ns_texts / sizeof *ns_texts);';

        return implode("\n", $lines) . "\n";
    }

    // ───────────────────────────── the vocabulary ─────────────────────────────

    /** @return string */
    private static function vocabHeader(): string
    {
        $lines = [self::HEADER, '#ifndef NS_VOCAB_H', '#define NS_VOCAB_H', '', '#include "markup.h"', ''];
        $lines[] = '/* the site\'s own elements (Tag) */';
        foreach (Tag::cases() as $tag) {
            $lines[] = 'extern const CSERVE_TAG ns_tag_' . self::ident($tag->value) . ';';
        }
        $lines[] = '';
        $lines[] = '/* its own attributes, by the enum that names each */';
        foreach (self::ATTRIBUTES as $prefix => $enum) {
            foreach ($enum::cases() as $attribute) {
                $lines[] = "extern const CSERVE_ATTR ns_attr_{$prefix}_" . self::ident($attribute->value) . ';';
            }
        }
        $lines[] = '';
        $lines[] = '/* its classes (CssClass) */';
        foreach (CssClass::cases() as $class) {
            $lines[] = '#define NS_CLASS_' . strtoupper(self::ident($class->value)) . ' ' . self::c($class->value);
        }
        $lines[] = '';
        $lines[] = '#endif';

        return implode("\n", $lines) . "\n";
    }

    /** @return string */
    private static function vocab(): string
    {
        $lines = [self::HEADER, '#include "vocab.h"', ''];
        foreach (Tag::cases() as $tag) {
            // A site's element is none of HTML's kinds: not void, not phrasing, not inline.
            $lines[] = sprintf('const CSERVE_TAG ns_tag_%s = {%s, 0};', self::ident($tag->value), self::c($tag->value));
        }
        foreach (self::ATTRIBUTES as $prefix => $enum) {
            foreach ($enum::cases() as $attribute) {
                $lines[] = sprintf(
                    'const CSERVE_ATTR ns_attr_%s_%s = {%s, %d};',
                    $prefix,
                    self::ident($attribute->value),
                    self::c($attribute->attribute()),
                    $attribute->isUrl() ? 1 : 0,
                );
            }
        }

        return implode("\n", $lines) . "\n";
    }

